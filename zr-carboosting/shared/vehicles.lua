-- VEHICLE IMAGE HANDLER
-- ═══════════════════════════════════════════════════════════════════════════════
function GetVehicleImage(imageName)
    -- Try webp first, then png
    local webpPath = ('html/img/%s.webp'):format(imageName)
    local pngPath = ('html/img/%s.png'):format(imageName)
    
    -- In NUI, we return the path that will be checked client-side
    return {
        webp = ('%s.webp'):format(imageName),
        png = ('%s.png'):format(imageName),
        fallback = 'default.png'
    }
end

-- ═══════════════════════════════════════════════════════════════════════════════
-- VEHICLE UTILITIES
-- ═══════════════════════════════════════════════════════════════════════════════
function GetRandomVehicle(class)
    local vehicles = Config.Vehicles[class]
    if not vehicles or #vehicles == 0 then
        return nil
    end
    return vehicles[math.random(#vehicles)]
end

function GetVehicleByModel(model)
    for class, vehicles in pairs(Config.Vehicles) do
        for _, vehicle in ipairs(vehicles) do
            if vehicle.model == model then
                return vehicle, class
            end
        end
    end
    return nil, nil
end

function GetAllVehiclesForClass(class)
    return Config.Vehicles[class] or {}
end

function GetVehicleCount(class)
    if class then
        return #(Config.Vehicles[class] or {})
    end
    
    local total = 0
    for _, vehicles in pairs(Config.Vehicles) do
        total = total + #vehicles
    end
    return total
end
